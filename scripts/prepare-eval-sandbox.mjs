#!/usr/bin/env node
/**
 * Creates a Charter-only eval workspace (symlinks) without opencode/ or other reference trees.
 * Use via CHARTER_EVAL_ROOT or the live eval wrapper script.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sandbox = path.join(root, '.charter-ai', 'eval-sandbox')

/** Paths the read-accuracy fixtures need; opencode/ is intentionally omitted. */
const ENTRIES = [
  'extension',
  'src',
  'package.json',
  'vite.config.ts',
  'tsconfig.json',
  'tsconfig.app.json',
  'tsconfig.extension.json',
  'tsconfig.node.json',
]

function linkEntry(name) {
  const src = path.join(root, name)
  if (!fs.existsSync(src)) {
    console.warn(`skip (missing): ${name}`)
    return
  }
  const dest = path.join(sandbox, name)
  const type = fs.statSync(src).isDirectory() ? 'dir' : 'file'
  fs.symlinkSync(src, dest, type)
}

if (fs.existsSync(sandbox)) {
  fs.rmSync(sandbox, { recursive: true, force: true })
}
fs.mkdirSync(sandbox, { recursive: true })

for (const name of ENTRIES) linkEntry(name)

fs.writeFileSync(
  path.join(sandbox, '.charter-eval-sandbox'),
  [
    'Charter-only eval workspace.',
    'Generated by scripts/prepare-eval-sandbox.mjs',
    'opencode/ and other reference trees are excluded so live eval measures Charter AI only.',
    '',
  ].join('\n'),
  'utf-8',
)

console.log(`Eval sandbox ready: ${sandbox}`)
console.log(`  Linked: ${ENTRIES.join(', ')}`)
console.log('  Run live eval with: CHARTER_EVAL_ROOT=.charter-ai/eval-sandbox npm run eval:read-accuracy:live:report')
